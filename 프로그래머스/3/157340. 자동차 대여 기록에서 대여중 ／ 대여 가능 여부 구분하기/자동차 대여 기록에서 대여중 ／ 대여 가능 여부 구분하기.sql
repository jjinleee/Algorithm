SELECT CAR_ID,
CASE WHEN S>0 THEN '대여중' ELSE '대여 가능' END AS AVAILABILITY
FROM (
    SELECT CAR_ID, 
    SUM(CASE WHEN DATE '2022-10-16'>= START_DATE AND  DATE '2022-10-16'<=END_DATE THEN 1 
        ELSE 0 END) AS S
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    GROUP BY CAR_ID
)
 
ORDER BY CAR_ID DESC