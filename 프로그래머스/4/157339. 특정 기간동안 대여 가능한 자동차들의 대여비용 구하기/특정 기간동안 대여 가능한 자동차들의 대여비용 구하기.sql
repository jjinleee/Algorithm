SELECT CAR_ID, C.CAR_TYPE, (30*DAILY_FEE*(100.0-DISCOUNT_RATE)/100)  AS FEE
FROM CAR_RENTAL_COMPANY_CAR C JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN P ON C.CAR_TYPE=P.CAR_TYPE AND P.DURATION_TYPE='30일 이상'
WHERE C.CAR_TYPE IN ('세단','SUV') AND
CAR_ID NOT IN (
    SELECT CAR_ID 
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE START_DATE<DATE '2022-12-01'AND END_DATE>DATE '2022-11-01'
) AND 30*DAILY_FEE*(100-DISCOUNT_RATE)/100 >= 500000 AND 30*DAILY_FEE*(100-DISCOUNT_RATE)/100<2000000
ORDER BY FEE DESC, CAR_TYPE,  CAR_ID DESC